package dev.agent.burp.tools;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import dev.agent.burp.core.Args;
import dev.agent.burp.core.Tool;
import dev.agent.burp.core.ToolContext;
import dev.agent.burp.json.Json;

/** {@code get_collaborator_payload} and {@code poll_collaborator}: the only out-of-band channel. */
public final class CollaboratorTools {

    public static final class GetPayload implements Tool {
        @Override
        public String name() {
            return "get_collaborator_payload";
        }

        @Override
        public Map<String, Object> handle(ToolContext ctx, Args args) {
            int count = args.integer("count", 1, 1, 20);
            String note = args.str("note", null);
            if (note != null && note.isBlank()) {
                note = null;
            }
            List<Map<String, Object>> payloads = ctx.collab().generate(count, note);
            return Json.obj(
                    "payloads", payloads,
                    "count", payloads.size(),
                    "polling_hint", "Trigger the payload in-target, then poll_collaborator at least 60 s later, again after a delay, "
                            + "and once more before closing the engagement. DNS-only hits prove reachability; HTTP hits are the strong signal.");
        }
    }

    public static final class Poll implements Tool {
        @Override
        public String name() {
            return "poll_collaborator";
        }

        @Override
        public Map<String, Object> handle(ToolContext ctx, Args args) throws InterruptedException {
            String payloadId = args.str("payload_id", null);
            if (payloadId != null && payloadId.isBlank()) {
                payloadId = null;
            }
            String type = args.choice("interaction_type", null, "dns", "http", "smtp");
            int wait = args.integer("wait_seconds", 0, 0, 120);
            String since = args.str("since", null);
            if (since != null && since.isBlank()) {
                since = null;
            }
            int limit = args.integer("limit", 50, 1, 500);
            boolean known = payloadId == null || ctx.collab().noteFor(payloadId) != null;

            Map<String, Object> polled = ctx.collab().poll(payloadId, type, since, wait);
            @SuppressWarnings("unchecked")
            List<Map<String, Object>> interactions = (List<Map<String, Object>>) polled.get("interactions");
            List<Map<String, Object>> shown = interactions.size() <= limit
                    ? interactions
                    : new ArrayList<>(interactions.subList(interactions.size() - limit, interactions.size()));
            return Json.obj(
                    "payload_id", payloadId,
                    "known_payload", known,
                    "interaction_type", type,
                    "since", since,
                    "interactions", shown,
                    "count", shown.size(),
                    "total_matches", interactions.size(),
                    "truncated", interactions.size() > shown.size(),
                    "waited_seconds", polled.get("waited_seconds"),
                    "hint", known ? polled.get("hint")
                            : "payload_id " + payloadId + " was not generated by this bridge instance's registry (it may come from an earlier "
                            + "session); polling it still works, but interactions carry no note.");
        }
    }

    private CollaboratorTools() {
    }
}
