# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def _hdr(resp: dict, name: str) -> str | None:
    for h in resp.get("headers", []):
        if h.get("name", "").lower() == name.lower():
            return h.get("value")
    return None


def _cookies(resp: dict) -> list[str]:
    out = []
    for h in resp.get("headers", []):
        if h.get("name", "").lower() == "set-cookie":
            out.append(h.get("value", ""))
    return out


def _vendor_hit(sig: dict, resp: dict) -> list[str]:
    ev = []
    for name, val in sig.get("headers", {}).items():
        got = _hdr(resp, name)
        if got is not None and (val is None or val.lower() in got.lower()):
            ev.append(f"header {name}: {got[:60]}")
    body = (resp.get("body") or "")[:4000].lower()
    for marker in sig.get("body", []):
        if marker.lower() in body:
            ev.append(f"body marker '{marker}'")
    for c in _cookies(resp):
        for pref in sig.get("cookies", []):
            if c.lower().startswith(pref.lower()):
                ev.append(f"cookie {pref}*")
    return ev


def classify_response(resp: dict) -> dict:
    """Vendor fingerprint + verdict (normal / blocked / challenge / rate_limited)."""
    hits = []
    for sig in SIGNATURES:
        ev = _vendor_hit(sig, resp)
        if ev:
            conf = "high" if len(ev) >= 2 else sig.get("confidence", "low")
            hits.append({"vendor": sig["vendor"], "confidence": conf, "evidence": ev[:6]})
    hits.sort(key=lambda h: len(h["evidence"]), reverse=True)

    status = resp.get("status") or 0
    body = (resp.get("body") or "").lower()
    challenge = None
    for kind, patterns in CHALLENGE_MARKERS:
        if any(re.search(p, resp.get("body") or "", re.I) for p in patterns[:2]):
            m = re.search(patterns[0], resp.get("body") or "", re.I)
            challenge = {"type": kind, "sitekey": m.group(1) if m and m.groups() else None}
            break

    if challenge and status in (403, 503, 429):
        verdict = "challenge"
    elif status == 429:
        verdict = "rate_limited"
    elif status in (403, 406, 412, 501, 503) and hits:
        verdict = "blocked"
    elif status in (403, 406, 412) and any(
            m in body for m in ["access denied", "request blocked", "not acceptable", "forbidden"]):
        verdict = "blocked"
    else:
        verdict = "normal"
    return {"vendors": hits, "verdict": verdict, "challenge": challenge, "status": status}


def _is_block_like(resp: dict, baseline_verdict: str | None = None) -> bool:
    v = classify_response(resp)
    return v["verdict"] in ("blocked", "challenge") or (
        baseline_verdict == "blocked" and v["verdict"] == "rate_limited")


# ---------------------------------------------------------------------------
# waf_fingerprint handler (was WafCore.waf_fingerprint)
# ---------------------------------------------------------------------------
def waf_fingerprint(bridge: BridgeClient, url: str | None = None,
                    response: dict | None = None) -> dict:
    if not response and not url:
        raise WafError("provide url or response",
                       "url: one benign GET via the bridge; response: an inline {status,headers,body} you already have (Tier 0).")
    if response:
        transport = "inline (no request sent)"
    else:
        response = bridge.request("GET", url, note=f"WAF fingerprint GET {url}")
        transport = response.get("transport")
    c = classify_response(response)
    return {"ok": True, "data": {
        "classification": c, "transport": transport,
        "guidance": {
            "normal": "no WAF evidence on this response — still run waf_probe before payload work (W-2); edge rules often trigger only on payloads",
            "challenge": f"{c['challenge']['type'] if c['challenge'] else 'js'} challenge — follow §12 CAPTCHA handling (captcha_detect first)",
            "blocked": "block page — record vendor in attack-surface.md; waf_adapt on the specific request that got blocked (W-3)",
            "rate_limited": "rate limited — back off (P12 rules); never evade, coordinate via the program if limits block legitimate tests",
        }[c["verdict"]],
    }}
